"""Качество готового ролика — общая настройка программы.

Ролик всегда СКАЧИВАЕТСЯ в лучшем доступном качестве: из плохого исходника
хорошего результата не собрать, а разница в весе исходников копеечная.
Настройка влияет на то, каким собирается ГОТОВЫЙ ролик — тот, что уходит
в канал.

Почему вместе с размером кадра меняется и crf: один и тот же crf на меньшем
кадре выглядит хуже — каждый артефакт занимает большую долю картинки. Поэтому
у 720p и 480p crf на единицу ниже, жмём чуть аккуратнее.

Поправка именно −1, а не больше: замеры на 30-секундном ролике показали, что
−4 на 480p раздувает файл с 30% до 47% от веса 1080p, то есть съедает почти
весь смысл выбирать 480p. При −1 остаётся 33%.

Пресеты уникализации исторически кодируют с разным crf (reels 23, crop 20,
tiktok 23 — см. комментарии в processors/*.py, там это обосновано составом
кадра). Настройка не затирает эту разницу, а сдвигает её: crf_for() берёт
базовый crf пресета и применяет к нему поправку выбранного качества.
"""

# Размер кадра и поправка к crf относительно 1080p. Размеры записаны явно,
# а не считаются по пропорции: 480 на 9:16 даёт 853.33, и любое округление
# слегка сплющивает картинку. 480×854 — стандартный вертикальный 480p.
_LEVELS: dict[str, dict] = {
    "1080p": {"size": (1080, 1920), "crf_shift": 0,
              "label": "1080p — исходное качество"},
    "720p":  {"size": (720, 1280), "crf_shift": -1,
              "label": "720p — файл примерно в полтора раза легче"},
    "480p":  {"size": (480, 854), "crf_shift": -1,
              "label": "480p — файл примерно втрое легче"},
}

DEFAULT = "1080p"          # как было до появления настройки


def levels() -> list[tuple[str, str]]:
    """[(ключ, подпись для списка)] в порядке от лучшего к меньшему."""
    return [(key, cfg["label"]) for key, cfg in _LEVELS.items()]


def current() -> str:
    """Выбранное качество (ключ). Незнакомое значение → DEFAULT."""
    from app import storage
    value = storage.kv_get("output_quality", DEFAULT)
    return value if value in _LEVELS else DEFAULT


def set_current(key: str) -> None:
    from app import storage
    if key in _LEVELS:
        storage.kv_set("output_quality", key)


def size(key: str | None = None) -> tuple[int, int]:
    """Размер кадра готового ролика (ширина, высота)."""
    return _LEVELS[key or current()]["size"]


def width(key: str | None = None) -> int:
    return size(key)[0]


def height(key: str | None = None) -> int:
    return size(key)[1]


def scale_args(key: str | None = None) -> list[str]:
    """Аргументы ffmpeg для уменьшения готового кадра, или [] для 1080p.

    Пресеты собирают кадр в 1080×1920 — под этот размер подобраны и фильтры,
    и размер вотермарка. Уменьшаем в самом конце, одним `-s`: так не нужно
    трогать выверенные цепочки фильтров в трёх пресетах, а картинка выходит
    та же, только меньше.
    """
    if (key or current()) == DEFAULT:
        return []
    w, h = size(key)
    return ["-s", f"{w}x{h}"]


def crf_for(base_crf: int, key: str | None = None) -> int:
    """Crf пресета с поправкой на выбранное качество.

    Держим в разумных границах: ниже 14 файл раздувается без видимой пользы,
    выше 30 картинка сыпется.
    """
    value = base_crf + _LEVELS[key or current()]["crf_shift"]
    return max(14, min(30, value))
